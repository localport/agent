var updateVectors = flag.Bool("update", false, "rewrite testdata/handshake_vectors.json")

const vectorsPath = "testdata/handshake_vectors.json"

// handshakeVectors is the cross-language fixture the browser session library
// checks itself against. Binary values are lowercase hex except the ticket
// and the accept message, which are given as sent on the wire.
type handshakeVectors struct {
	Description            string        `json:"description"`
	TicketSigningPublicKey string        `json:"ticket_signing_public_key"`
	Ticket                 string        `json:"ticket"`
	ClientX25519Private    string        `json:"client_x25519_private"`
	ClientX25519Public     string        `json:"client_x25519_public"`
	ClientMLKEMSeed        string        `json:"client_mlkem_seed"`
	ClientMLKEMEncapKey    string        `json:"client_mlkem_encapsulation_key"`
	DeviceP256Private      string        `json:"device_p256_private"`
	DeviceSPKIDER          string        `json:"device_spki_der"`
	AgentX25519Private     string        `json:"agent_x25519_private"`
	MLKEMEncapsulationRand string        `json:"mlkem_encapsulation_random"`
	Accept                 AcceptMessage `json:"accept"`
	SharedSecretX25519     string        `json:"ss_x"`
	SharedSecretMLKEM      string        `json:"ss_pq"`
	Transcript             string        `json:"transcript"`
	KeyC2A                 string        `json:"k_c2a"`
	KeyA2C                 string        `json:"k_a2c"`
	Records                []vectorRec   `json:"records"`
}

// vectorRec is one sealed record; Sealed includes the uint32 length prefix
// and Counter is its direction's record number.
type vectorRec struct {
	Direction string `json:"direction"`
	Counter   int    `json:"counter"`
	Plaintext string `json:"plaintext"`
	Sealed    string `json:"sealed"`
}

func generateVectors(t *testing.T) []byte {
	t.Helper()
	f := newFixture(t, "vector")
	raw := sign(t, f.ticketKey, f.payload())
	tk, err := VerifyTicket(raw, f.lookup, f.deviceID(), testNow)
	if err != nil {
		t.Fatal(err)
	}
	eph, err := ecdh.X25519().NewPrivateKey(fixed("vector agent x25519"))
	if err != nil {
		t.Fatal(err)
	}
	encRand := fixed("vector mlkem encapsulation")
	var ssPQ []byte
	encapsulate := func(ek *mlkem.EncapsulationKey768) ([]byte, []byte, error) {
		ss, ct, err := mlkemtest.Encapsulate768(ek, encRand)
		ssPQ = ss
		return ss, ct, err
	}
	msg, keys, err := accept(tk, f.device, eph, encapsulate, nil)
	if err != nil {
		t.Fatal(err)
	}
	clientKeys, err := Open(raw, f.spkiDER, msg, f.client)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(clientKeys.C2A, keys.C2A) || !bytes.Equal(clientKeys.A2C, keys.A2C) {
		t.Fatal("vector keys disagree")
	}
	ssX, err := eph.ECDH(tk.clientX)
	if err != nil {
		t.Fatal(err)
	}
	aPub := eph.PublicKey().Bytes()
	ct := mustDecode(t, msg.CTMLKEM)
	tr := transcript(raw, aPub, ct)

	type plain struct {
		dir  string
		typ  MessageType
		body []byte
	}
	plains := []plain{
		{"c2a", TypeStart, []byte(`{"cols":80,"rows":24}`)},
		{"c2a", TypeData, []byte("echo hello\n")},
		{"a2c", TypeData, []byte("hello\n")},
		{"a2c", TypeActivity, nil},
		{"c2a", TypeClose, []byte(`{"reason":"client_closed"}`)},
	}
	c2a, a2c := &recorder{}, &recorder{}
	client, err := keys.ClientChannel(c2a)
	if err != nil {
		t.Fatal(err)
	}
	agent, err := keys.AgentChannel(a2c)
	if err != nil {
		t.Fatal(err)
	}
	var records []vectorRec
	for _, p := range plains {
		ch, rec := client, c2a
		if p.dir == "a2c" {
			ch, rec = agent, a2c
		}
		if err := ch.WriteMessage(p.typ, p.body); err != nil {
			t.Fatal(err)
		}
		records = append(records, vectorRec{
			Direction: p.dir,
			Counter:   len(rec.records) - 1,
			Plaintext: hex.EncodeToString(append([]byte{byte(p.typ)}, p.body...)),
			Sealed:    hex.EncodeToString(rec.records[len(rec.records)-1]),
		})
	}

	v := handshakeVectors{
		Description: "localport session handshake: Ed25519 ticket, X25519 + ML-KEM-768 hybrid, " +
			"ECDSA P-256 P1363 device signature (RFC 6979), HKDF-SHA256, ChaCha20-Poly1305 records. " +
			"Generated by agent/internal/session/vectors_test.go; regenerate with go test ./internal/session -run TestHandshakeVectors -update.",
		TicketSigningPublicKey: hex.EncodeToString(f.ticketKey.Public().(ed25519.PublicKey)),
		Ticket:                 string(raw),
		ClientX25519Private:    hex.EncodeToString(f.client.X25519.Bytes()),
		ClientX25519Public:     hex.EncodeToString(f.client.X25519.PublicKey().Bytes()),
		ClientMLKEMSeed:        hex.EncodeToString(f.mlkemSeed),
		ClientMLKEMEncapKey:    hex.EncodeToString(f.client.MLKEM.EncapsulationKey().Bytes()),
		DeviceP256Private:      hex.EncodeToString(fixed("vector device")),
		DeviceSPKIDER:          hex.EncodeToString(f.spkiDER),
		AgentX25519Private:     hex.EncodeToString(eph.Bytes()),
		MLKEMEncapsulationRand: hex.EncodeToString(encRand),
		Accept:                 *msg,
		SharedSecretX25519:     hex.EncodeToString(ssX),
		SharedSecretMLKEM:      hex.EncodeToString(ssPQ),
		Transcript:             hex.EncodeToString(tr[:]),
		KeyC2A:                 hex.EncodeToString(keys.C2A),
		KeyA2C:                 hex.EncodeToString(keys.A2C),
		Records:                records,
	}
	out, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return append(out, '\n')
}

func mustDecode(t *testing.T, s string) []byte {
	t.Helper()
	b, err := base64.RawURLEncoding.DecodeString(s)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// TestHandshakeVectors regenerates the vectors and requires the committed
// file to match byte for byte.
func TestHandshakeVectors(t *testing.T) {
	got := generateVectors(t)
	if *updateVectors {
		if err := os.MkdirAll(filepath.Dir(vectorsPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(vectorsPath, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s differs from the generated vectors; run with -update after an intended change", vectorsPath)
	}
}

// TestHandshakeVectorsOpen replays the committed vectors through the client
// side: the transcript hash and the sealed records must check out.
func TestHandshakeVectorsOpen(t *testing.T) {
	data, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	var v handshakeVectors
	if err := json.Unmarshal(data, &v); err != nil {
		t.Fatal(err)
	}
	f := newFixture(t, "vector")
	keys, err := Open([]byte(v.Ticket), f.spkiDER, &v.Accept, f.client)
	if err != nil {
		t.Fatal(err)
	}
	if hex.EncodeToString(keys.C2A) != v.KeyC2A || hex.EncodeToString(keys.A2C) != v.KeyA2C {
		t.Fatal("derived keys differ from the vectors")
	}
	tr := transcript([]byte(v.Ticket), mustDecode(t, v.Accept.AX25519), mustDecode(t, v.Accept.CTMLKEM))
	if hex.EncodeToString(tr[:]) != v.Transcript {
		t.Fatal("transcript differs from the vectors")
	}
	var c2a, a2c [][]byte
	for _, r := range v.Records {
		sealed, err := hex.DecodeString(r.Sealed)
		if err != nil {
			t.Fatal(err)
		}
		if r.Direction == "c2a" {
			c2a = append(c2a, sealed)
		} else {
			a2c = append(a2c, sealed)
		}
	}
	agent, err := keys.AgentChannel(struct {
		io.Reader
		io.Writer
	}{bytes.NewReader(bytes.Join(c2a, nil)), io.Discard})
	if err != nil {
		t.Fatal(err)
	}
	for range c2a {
		if _, err := agent.ReadMessage(); err != nil {
			t.Fatal(err)
		}
	}
	client, err := keys.ClientChannel(struct {
		io.Reader
		io.Writer
	}{bytes.NewReader(bytes.Join(a2c, nil)), io.Discard})
	if err != nil {
		t.Fatal(err)
	}
	for range a2c {
		if _, err := client.ReadMessage(); err != nil {
			t.Fatal(err)
		}
	}
}
